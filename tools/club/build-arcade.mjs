//   node tools/club/build-arcade.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const src = fs.readFileSync(path.join(ROOT, "public/index.html"), "utf8");
const lines = src.split("\n");
const find = (re, from = 0) => { for (let i = from; i < lines.length; i++) if (re.test(lines[i])) return i; throw new Error("not found: " + re); };

// the code: from the mini-games' own helpers ($mg) to the end of the game's script
const a = find(/^const \$mg=id=>document\.getElementById\(id\);/), b = find(/^<\/script>/, a);
let code = lines.slice(a, b).join("\n");
// the styles: the mini-game window (.mgx…) and the result card (.mg-result…)
const cssA = find(/^\.mgx\{/), cssB = (() => { let k = cssA; for (let i = cssA; i < cssA + 200; i++) if (/mgx|mg-/.test(lines[i])) k = i; return k; })();
const css = lines.slice(cssA, cssB + 1).join("\n") + "\n" + lines.filter((l) => /^\.mg-res|^\.mg-result/.test(l)).join("\n") + "\n" + lines.filter((l) => /^\.rain-coin|^\.coin-rain|@keyframes coinFall/.test(l)).join("\n");
// the screens
const mA = find(/<div class="mgx" id="mgOverlay"/), mB = find(/<div class="pcard petcard" id="petCard"/, mA);
const markup = lines.slice(mA, mB).join("\n");
const resA = find(/id="mgResult"/), resLine = lines[resA];
const colors = (() => { const i = find(/^const COLORS=\[/); let j = i; while (!/\]\];\s*$/.test(lines[j])) j++; return lines.slice(i, j + 1).join("\n"); })();
const coinSvg = lines[find(/^const COIN_SVG=/)];
const rain = (() => { const i = find(/^function coinRain\(/); let j = i + 1; while (!/}\s*$/.test(lines[j])) j++; return lines.slice(i, j + 1).join("\n"); })();

